# Utilizando separador sep - separa os textos do print
print("2026","09","15",sep="-")
print("SENAI","Python","Tarde",sep=" | ")

# Utilizando end - alterar o final da linha
print("Carregando o sistema...",end=" ")
print("[Concluído]")

# Utilizando quebra de linha "\n\n"
print("---Nomes Alunos---\n\n")
print("Diego Gonzaga")
