# ----- Idade em Dias -----

# Solicitando a idade do usuário
idade_anos = int(input("Digite sua idade em anos: "))

# Convertendo anos em dias
dias_vividos = idade_anos * 365

# Apresentando os dias vividos ao usuário
print(f"Você tem {idade_anos} anos e já viveu {dias_vividos} dias")